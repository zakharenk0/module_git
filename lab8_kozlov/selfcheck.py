"""Локальная версия ячейки самопроверки из рабочей тетради (раздел 8).

Запуск:  python selfcheck.py
Результат печатается и сохраняется в SelfCheckReport.md — готов для вставки
в описание pull request.
"""
import datetime
import os
import re
import subprocess

import pandas as pd

# --- заполненные параметры ячейки 6.1 и раздела 8 ---
ФИО_исполнителя = "Козлов (GitHub: zakharenk0)"
Группа_исполнителя = "GI-41 (уточнить номер группы)"
ТАБЛИЦА_ПРОСЛЕЖИВАЕМОСТИ_ЗАПОЛНЕНА = True
ВОПРОСЫ_И_ВЫВОДЫ_ЗАПОЛНЕНЫ = True

ССЫЛКА_НА_МОЁ_РЕВЬЮ = "https://github.com/VeronikaZmushko/Lab8_Code_Review/pull/1#pullrequestreview-6025854716"
ССЫЛКА_НА_МОЙ_PR = "https://github.com/vgkozlov/stations-gi41/pull/74"
ЗАМЕЧАНИЙ_ОСТАВЛЕНО = 7
ЗАМЕЧАНИЙ_ПОЛУЧЕНО = 0
ЗАМЕЧАНИЙ_ПРИНЯТО = 0

JAVA = os.environ.get(
    "JAVA17",
    r"C:\Users\Maksim\AppData\Local\Temp\opencode\jdk17\jdk-17.0.21.1+2\bin\java.exe",
)
if not os.path.exists(JAVA):
    JAVA = "java"

ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ = ["Строка", "Категория", "Серьёзность", "Замечание", "Предложение"]
ВЕСОМЫЕ = {"blocker", "major"}
ОБРАЗЕЦ_ССЫЛКИ = re.compile(r"https://github\.com/[\w.-]+/[\w.-]+/pull/\d+")

ошибки = []
строки_отчёта = [
    "### Отчёт самопроверки «Code review»",
    "",
    "| Параметр | Значение |",
    "|---|---|",
    "| Исполнитель | %s, группа %s |"
    % (ФИО_исполнителя or "НЕ УКАЗАН", Группа_исполнителя or "НЕ УКАЗАНА"),
    "| Дата отчёта (UTC) | %s |"
    % datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M"),
]

# --- 1. таблица замечаний ---
if not os.path.exists("ReviewNotes.csv"):
    ошибки.append("нет файла ReviewNotes.csv")
    строки_отчёта.append("| Таблица замечаний | ОТСУТСТВУЕТ |")
else:
    таблица = pd.read_csv("ReviewNotes.csv").fillna("")
    отсутствующие_поля = [п for п in ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ if п not in таблица.columns]
    if отсутствующие_поля:
        ошибки.append("в ReviewNotes.csv нет колонок: " + ", ".join(отсутствующие_поля))
        строки_отчёта.append("| Таблица замечаний | нет колонок: %s |" % ", ".join(отсутствующие_поля))
    else:
        маска_заполненных = таблица[ОБЯЗАТЕЛЬНЫЕ_ПОЛЯ].astype(str).apply(
            lambda строка: all(значение.strip() for значение in строка), axis=1
        )
        заполненные = таблица[маска_заполненных]
        весомых = (
            заполненные["Серьёзность"].astype(str).str.strip().str.lower().isin(ВЕСОМЫЕ).sum()
        )
        коротких = (заполненные["Предложение"].astype(str).str.len() < 20).sum()
        строки_отчёта.append(
            "| Таблица замечаний | записей %d, заполненных %d, весомых %d |"
            % (len(таблица), len(заполненные), весомых)
        )
        if len(заполненные) < 8:
            ошибки.append("полностью заполненных замечаний %d, требуется не менее 8" % len(заполненные))
        if весомых < 3:
            ошибки.append("замечаний blocker/major %d, требуется не менее 3" % весомых)
        if коротких:
            ошибки.append("замечаний без содержательного предложения: %d" % коротких)


# --- 2. исправленный код ---
def запустить_java(имя_файла):
    if not os.path.exists(имя_файла):
        return False, "файл отсутствует"
    завершение = subprocess.run(
        [JAVA, "-Dfile.encoding=UTF-8", имя_файла],
        capture_output=True, text=True, timeout=180, encoding="utf-8",
    )
    вывод = завершение.stdout + завершение.stderr
    значимые = [с for с in вывод.splitlines() if с.strip() and not с.startswith("Picked up")]
    if завершение.returncode != 0:
        return False, "аварийное завершение: " + (значимые[0][:90] if значимые else "без сообщения")
    if "[FAIL]" in вывод:
        return False, "не пройдено проверок: %d" % вывод.count("[FAIL]")
    успешных = вывод.count("[OK]")
    if успешных < 5:
        return False, "самопроверок в файле только %d, требуется не менее 5" % успешных
    return True, "самопроверок пройдено: %d" % успешных


успех_кода, пояснение_кода = запустить_java("ShiftPlanFixed.java")
строки_отчёта.append(
    "| `ShiftPlanFixed.java` | %s — %s |"
    % ("пройдено" if успех_кода else "НЕ ПРОЙДЕНО", пояснение_кода)
)
if not успех_кода:
    ошибки.append("ShiftPlanFixed.java: " + пояснение_кода)

исходный_текст = open("ShiftPlanFixed.java", encoding="utf-8").read()
if "==" in исходный_текст and re.search(r'==\s*"', исходный_текст):
    ошибки.append("в ShiftPlanFixed.java осталось сравнение строки через ==")

# --- 3. ревью на GitHub ---
строки_отчёта += [
    "| Ревью на чужой запрос | %s |" % (ССЫЛКА_НА_МОЁ_РЕВЬЮ or "НЕ УКАЗАНО"),
    "| Свой запрос | %s |" % (ССЫЛКА_НА_МОЙ_PR or "НЕ УКАЗАН"),
    "| Замечаний оставлено / получено / принято | %d / %d / %d |"
    % (ЗАМЕЧАНИЙ_ОСТАВЛЕНО, ЗАМЕЧАНИЙ_ПОЛУЧЕНО, ЗАМЕЧАНИЙ_ПРИНЯТО),
    "| Таблица прослеживаемости | %s |"
    % ("заполнена" if ТАБЛИЦА_ПРОСЛЕЖИВАЕМОСТИ_ЗАПОЛНЕНА else "НЕ ЗАПОЛНЕНА"),
    "| Вопросы и выводы | %s |"
    % ("заполнены" if ВОПРОСЫ_И_ВЫВОДЫ_ЗАПОЛНЕНЫ else "НЕ ЗАПОЛНЕНЫ"),
]

for подпись, ссылка in [("ревью", ССЫЛКА_НА_МОЁ_РЕВЬЮ), ("своего запроса", ССЫЛКА_НА_МОЙ_PR)]:
    if not ОБРАЗЕЦ_ССЫЛКИ.search(str(ссылка)):
        ошибки.append("ссылка %s не похожа на адрес pull request" % подпись)
if ЗАМЕЧАНИЙ_ОСТАВЛЕНО < 5:
    ошибки.append("оставлено замечаний %d, требуется не менее 5" % ЗАМЕЧАНИЙ_ОСТАВЛЕНО)
if ЗАМЕЧАНИЙ_ПОЛУЧЕНО and ЗАМЕЧАНИЙ_ПРИНЯТО > ЗАМЕЧАНИЙ_ПОЛУЧЕНО:
    ошибки.append("принято замечаний больше, чем получено")
if not ФИО_исполнителя.strip() or not Группа_исполнителя.strip():
    ошибки.append("не указаны ФИО и группа")
if not ТАБЛИЦА_ПРОСЛЕЖИВАЕМОСТИ_ЗАПОЛНЕНА:
    ошибки.append("не заполнена таблица прослеживаемости")
if not ВОПРОСЫ_И_ВЫВОДЫ_ЗАПОЛНЕНЫ:
    ошибки.append("не заполнены контрольные вопросы и выводы")

отчёт = "\n".join(строки_отчёта)
print(отчёт)
with open("SelfCheckReport.md", "w", encoding="utf-8") as файл:
    файл.write(отчёт + "\n")
print("\nСкопируйте отчёт выше в описание pull request.\n")

assert not ошибки, "Работа не готова к сдаче: " + "; ".join(ошибки)
print("Самопроверка пройдена: работа готова к сдаче.")
